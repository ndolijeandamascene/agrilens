"""
AgriLens Decision Support & Impact Tracking Models.
Provides evidence-based agricultural recommendations, multi-stakeholder action plans,
and empirical outcome monitoring for Rwanda (NISR 2026 Big Data Hackathon Track 1).
"""
from decimal import Decimal
from django.db import models
from django.conf import settings


class StakeholderType(models.TextChoices):
    GOVERNMENT = 'GOVERNMENT', 'Government & Policy Makers (MINAGRI/District)'
    BANK = 'BANK', 'Agricultural Lenders & Commercial Banks'
    INSURER = 'INSURER', 'Crop & Agricultural Insurers'
    AGRIBUSINESS = 'AGRIBUSINESS', 'Agribusiness & Food Processors'


class PriorityLevel(models.TextChoices):
    CRITICAL = 'CRITICAL', 'Critical Priority'
    HIGH = 'HIGH', 'High Priority'
    MEDIUM = 'MEDIUM', 'Medium Priority'
    LOW = 'LOW', 'Low Priority'


class RecommendationStatus(models.TextChoices):
    GENERATED = 'GENERATED', 'Generated by Analytical Engine'
    UNDER_REVIEW = 'UNDER_REVIEW', 'Under Institutional Review'
    APPROVED = 'APPROVED', 'Approved for Action'
    REJECTED = 'REJECTED', 'Rejected / Not Applicable'
    ASSIGNED = 'ASSIGNED', 'Assigned to Stakeholder'
    IN_PROGRESS = 'IN_PROGRESS', 'Action In Progress'
    COMPLETED = 'COMPLETED', 'Completed & Evaluated'
    CANCELLED = 'CANCELLED', 'Cancelled'


class ActionStatus(models.TextChoices):
    PLANNED = 'PLANNED', 'Planned'
    ONGOING = 'ONGOING', 'Ongoing / In Execution'
    COMPLETED = 'COMPLETED', 'Completed'
    CANCELLED = 'CANCELLED', 'Cancelled'


class RecommendationRule(models.Model):
    """
    Parametric rule definition for deterministic decision generation.
    Enforces reproducible threshold logic across institutional stakeholders.
    """
    code = models.CharField(max_length=64, unique=True, db_index=True)
    title = models.CharField(max_length=255)
    target_stakeholder = models.CharField(max_length=30, choices=StakeholderType.choices)
    description = models.TextField(blank=True)
    parameters = models.JSONField(default=dict, blank=True, help_text="Configurable rule parameters and thresholds (JSON)")
    version = models.PositiveIntegerField(default=1)
    is_active = models.BooleanField(default=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['target_stakeholder', 'code']

    def __str__(self):
        return f"[{self.target_stakeholder}] {self.title} (v{self.version})"


class Recommendation(models.Model):
    """
    Specific evidence-driven recommendation generated from empirical NISR/MINAGRI indicators.
    Must always store complete data lineage and evidence metrics.
    """
    rule = models.ForeignKey(
        RecommendationRule,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='recommendations'
    )
    target_stakeholder = models.CharField(max_length=30, choices=StakeholderType.choices, db_index=True)
    district = models.ForeignKey(
        'geography.District',
        on_delete=models.CASCADE,
        null=True,
        blank=True,
        related_name='recommendations'
    )
    crop = models.ForeignKey(
        'agriculture.Crop',
        on_delete=models.CASCADE,
        null=True,
        blank=True,
        related_name='recommendations'
    )
    season = models.ForeignKey(
        'agriculture.AgriculturalSeason',
        on_delete=models.CASCADE,
        null=True,
        blank=True,
        related_name='recommendations'
    )
    priority = models.CharField(
        max_length=20,
        choices=PriorityLevel.choices,
        default=PriorityLevel.MEDIUM,
        db_index=True
    )
    title = models.CharField(max_length=255)
    problem_statement = models.TextField(help_text="Factual diagnosis grounded strictly in empirical survey microdata.")
    evidence_json = models.JSONField(
        default=dict,
        help_text="Detailed audit metrics: observed yield, benchmark yield, gap percentage, plot count, provenance lineage."
    )
    recommendation_text = models.TextField(help_text="Specific, actionable advisory grounded in agricultural best practices.")
    status = models.CharField(
        max_length=25,
        choices=RecommendationStatus.choices,
        default=RecommendationStatus.GENERATED,
        db_index=True
    )
    reviewer = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='reviewed_recommendations'
    )
    reviewed_at = models.DateTimeField(null=True, blank=True)
    review_notes = models.TextField(blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['-priority', '-created_at']
        indexes = [
            models.Index(fields=['target_stakeholder', 'status']),
            models.Index(fields=['district', 'crop', 'season']),
        ]

    def __str__(self):
        d_name = self.district.name if self.district else "National"
        c_name = self.crop.name if self.crop else "General"
        return f"[{self.get_target_stakeholder_display()}] {self.title} ({d_name} - {c_name})"

    @property
    def recommended_action(self):
        """Convenience alias for recommendation_text."""
        return self.recommendation_text

    @property
    def reviewer_display(self):
        """Safe human-readable reviewer name or fallback."""
        if self.reviewer:
            return self.reviewer.get_full_name() or self.reviewer.username
        return "Pending Review"


class ActionPlan(models.Model):
    """
    Institutional implementation action derived from an approved recommendation.
    Tracks accountability, assigned organizational units, and milestone deadlines.
    """
    recommendation = models.ForeignKey(
        Recommendation,
        on_delete=models.CASCADE,
        related_name='action_plans'
    )
    title = models.CharField(max_length=255)
    assigned_to = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='assigned_actions'
    )
    assigned_organization = models.CharField(
        max_length=255,
        blank=True,
        help_text="Responsible directorate or institution (e.g., MINAGRI Extension, District Agronomy, Bank Underwriting)"
    )
    target_date = models.DateField(null=True, blank=True)
    action_details = models.TextField(help_text="Detailed operational steps, resource allocations, and intervention scope.")
    status = models.CharField(
        max_length=20,
        choices=ActionStatus.choices,
        default=ActionStatus.PLANNED,
        db_index=True
    )
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['target_date', '-created_at']

    def __str__(self):
        return f"{self.title} ({self.get_status_display()})"

    @property
    def assignee_display(self):
        """Safe human-readable assigned entity or officer name."""
        if self.assigned_organization:
            return self.assigned_organization
        if self.assigned_to:
            return self.assigned_to.get_full_name() or self.assigned_to.username
        return "Unassigned"


class OutcomeMeasurement(models.Model):
    """
    Empirical monitoring record tracking pre- vs post-intervention yields across subsequent survey seasons.
    Strictly discloses that observed yield change is an empirical monitoring indicator,
    not a proven causal counterfactual impact evaluation.
    """
    action_plan = models.ForeignKey(
        ActionPlan,
        on_delete=models.CASCADE,
        related_name='outcomes'
    )
    district = models.ForeignKey(
        'geography.District',
        on_delete=models.CASCADE,
        related_name='outcome_measurements'
    )
    crop = models.ForeignKey(
        'agriculture.Crop',
        on_delete=models.CASCADE,
        related_name='outcome_measurements'
    )
    baseline_season = models.ForeignKey(
        'agriculture.AgriculturalSeason',
        on_delete=models.SET_NULL,
        null=True,
        related_name='+'
    )
    evaluation_season = models.ForeignKey(
        'agriculture.AgriculturalSeason',
        on_delete=models.SET_NULL,
        null=True,
        related_name='+'
    )
    baseline_yield_kg_per_ha = models.DecimalField(max_digits=10, decimal_places=2)
    evaluation_yield_kg_per_ha = models.DecimalField(max_digits=10, decimal_places=2)
    observed_yield_change_pct = models.DecimalField(max_digits=6, decimal_places=2)
    notes = models.TextField(blank=True)
    disclaimer = models.TextField(
        default="Observed post-action change is a descriptive monitoring metric and does not represent proven causal impact or counterfactual attribution."
    )
    measured_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-measured_at']

    def __str__(self):
        return f"Outcome for {self.district.name} ({self.crop.name}): {self.observed_yield_change_pct:+}%"

    @property
    def baseline_yield_kg_ha(self):
        return self.baseline_yield_kg_per_ha

    @property
    def evaluation_yield_kg_ha(self):
        return self.evaluation_yield_kg_per_ha

    def save(self, *args, **kwargs):
        if self.baseline_yield_kg_per_ha and self.evaluation_yield_kg_per_ha and self.observed_yield_change_pct is None:
            b = float(self.baseline_yield_kg_per_ha)
            e = float(self.evaluation_yield_kg_per_ha)
            if b > 0:
                self.observed_yield_change_pct = Decimal(str(round(((e - b) / b) * 100.0, 2)))
        super().save(*args, **kwargs)

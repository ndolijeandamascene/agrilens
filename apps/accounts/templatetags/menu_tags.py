@register.simple_tag
def resolve_menu_url(url_string):
    """
    Resolves a URL string that might contain query parameters or be a direct path.
    Example 1: 'accounts:user_list' -> '/accounts/users/'
    Example 2: 'data_management:manual_entry_list?status=pending' -> '/data-management/manual/?status=pending'
    Example 3: '/api/' -> '/api/'
    """
    if not url_string:
        return "#"

    if url_string.startswith("/"):
        return url_string

    params = ""
    view_name = url_string

    if "?" in url_string:
        view_name, params = url_string.split("?", 1)
        params = "?" + params

    try:
        return f"{reverse(view_name)}{params}"
    except NoReverseMatch:
        return "#"


@register.simple_tag
def is_menu_active(request, url_string):
    """
    Determines whether a menu link is currently active based on request.path or resolver match.
    """
    if not request or not url_string:
        return False

    resolved = resolve_menu_url(url_string)
    if resolved == "#":
        return False

    # Extract base path without query string for path comparison
    base_resolved = resolved.split("?")[0]
    
    # Exact root match
    if base_resolved == "/" and request.path == "/":
        return True
    
    # Non-root path prefix match
    if base_resolved != "/" and request.path.startswith(base_resolved):
        return True

    # Resolver match fallback
    view_name = url_string.split("?")[0]
    if request.resolver_match and request.resolver_match.view_name == view_name:
        return True

    return False


@register.simple_tag
def is_group_active(request, group):
    """
    Determines if any sub-item inside a group is active.
    Used for setting initial accordion expansion state.
    """
    if not group or not group.get("submenu"):
        return False
    for subitem in group["submenu"]:
        if is_menu_active(request, subitem.get("url")):
            return True
    return False


@register.simple_tag
def render_menu_icon(icon_name):
    """
    Renders SVG markup for the given icon name.
    """
    svg = ICONS.get(icon_name, ICONS["core"])
    return mark_safe(svg)
